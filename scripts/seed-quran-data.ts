// ── Juz boundaries (page where each Juz starts) ──────────────────────────────
// Saudi Madani Mushaf juz start pages — verified via qurancdn.com API
// (page containing the standard juz-boundary ayah, Hafs 'an 'Asim)
const JUZ_START_PAGES = [
  1, 22, 42, 62, 82, 102, 121, 142, 161, 182, 201, 222, 242, 262, 282,
  302, 322, 342, 362, 382, 402, 422, 442, 462, 482, 502, 522, 542, 562, 582,
];

function getJuzNumber(pageNumber: number): number {
  let juz = 30;
  for (let i = 0; i < JUZ_START_PAGES.length; i++) {
    if (pageNumber >= JUZ_START_PAGES[i]) {
      juz = i + 1;
    }
  }
  return juz;
}

function getHizbNumber(pageNumber: number, juzNumber: number): number {
  // Each juz has 2 hizb; pages per juz ≈ 20
  // Rough approximation: first half of juz = first hizb, second half = second hizb
  const juzStart = JUZ_START_PAGES[juzNumber - 1];
  const juzEnd = juzNumber < 30 ? JUZ_START_PAGES[juzNumber] - 1 : 604;
  const juzPages = juzEnd - juzStart + 1;
  const halfwayPage = juzStart + Math.floor(juzPages / 2);
  return pageNumber < halfwayPage ? (juzNumber - 1) * 2 + 1 : (juzNumber - 1) * 2 + 2;
}

