export async function main() {
  console.log('Seeding Quran reference data...');

  // Build surah lookup map
  const surahMap = new Map(SURAHS.map(([num, en, ar, _]) => [num, { en, ar }]));

  // Build all 604 page rows in memory
  const pageRows = PAGE_DATA.map(([pageNumber, surahNumber, ayahStart, isStartOfSurah]) => {
    const juzNumber = getJuzNumber(pageNumber);
    const hizbNumber = getHizbNumber(pageNumber, juzNumber);
    const surah = surahMap.get(surahNumber);
    if (!surah) throw new Error(`No surah data for surah ${surahNumber} (page ${pageNumber})`);
    return { pageNumber, juzNumber, hizbNumber, surahNumber, surahNameEn: surah.en, surahNameAr: surah.ar, ayahStart, isStartOfSurah };
  });

  // Upsert all 604 rows so existing incorrect data is overwritten on re-run.
  // Sequential upserts are acceptable at this size (~604 rows takes < 2 s).
  let upserted = 0;
  for (const row of pageRows) {
    await prisma.quranPage.upsert({
      where: { pageNumber: row.pageNumber },
      update: { juzNumber: row.juzNumber, hizbNumber: row.hizbNumber, surahNumber: row.surahNumber, surahNameEn: row.surahNameEn, surahNameAr: row.surahNameAr, ayahStart: row.ayahStart, isStartOfSurah: row.isStartOfSurah },
      create: row,
    });
    upserted++;
  }
  console.log(`✓ Upserted ${upserted} QuranPage rows`);

  // Tajweed rules — only 20 rows, sequential upsert is fine and preserves updates
  for (const rule of TAJWEED_RULES) {
    await prisma.tajweedRule.upsert({
      where: { id: rule.id },
      update: { nameEn: rule.nameEn, nameAr: rule.nameAr, category: rule.category as any, description: rule.description },
      create: { id: rule.id, nameEn: rule.nameEn, nameAr: rule.nameAr, category: rule.category as any, description: rule.description },
    });
  }
  console.log(`✓ Upserted ${TAJWEED_RULES.length} TajweedRule rows`);

  console.log('\nDone. Quran reference data is ready.');
}

// Only run directly (not when imported by another seed script).
// process.argv[1] is the entry point file; when this file IS the entry point,
// it contains "seed-quran-data". When imported, it contains the caller's path.
if (process.argv[1] && process.argv[1].includes('seed-quran-data')) {
  main()
    .catch(e => { console.error(e); process.exit(1); })
    .finally(() => prisma.$disconnect());
}
